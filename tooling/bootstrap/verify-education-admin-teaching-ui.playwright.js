// Real original-auth browser regression. All created teaching data is explicitly TEST-only.
// Run from repository root; no API interception, token/credential output, or screenshots of login.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const cache = path.join(process.env.LOCALAPPDATA, 'npm-cache', '_npx');
const modulePath = process.env.PLAYWRIGHT_MODULE || fs.readdirSync(cache).map(name => path.join(cache, name, 'node_modules/playwright')).find(dir => fs.existsSync(path.join(dir, 'package.json')));
if (!modulePath) throw new Error('Install Playwright CLI or set PLAYWRIGHT_MODULE.');
const { chromium } = require(modulePath);
const env = Object.fromEntries(fs.readFileSync('.runtime/foundation.env', 'utf8').trim().split(/\r?\n/).map(line => { const i = line.indexOf('='); return [line.slice(0, i), line.slice(i + 1)]; }));
const fixture = JSON.parse(fs.readFileSync('.runtime/education-flow-report.json', 'utf8')).fixtures;
const base = 'http://127.0.0.1:48080';
const marker = `TEST-TEACHING-UI-${Date.now()}`;
const report = { timestamp: new Date().toISOString(), checks: [], fixtures: {} };
const pass = name => { report.checks.push(name); console.log(`PASS: ${name}`); };
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
let admin, member;
async function api(route, body) {
  const response = await page.request.fetch(base + route, { method: body ? 'POST' : 'GET', headers: { 'tenant-id': '1', terminal: '10', ...(route.includes('/auth/login') ? {} : { Authorization: `Bearer ${route.startsWith('/admin') ? admin : member}` }) }, ...(body ? { data: body } : {}) });
  const result = await response.json();
  assert.equal(result.code, 0, `${route}: ${result.msg}`);
  return result.data;
}
const post = (route, body) => api('/admin-api/edu' + route, body);
const get = route => api('/admin-api/edu' + route);
try {
  admin = (await api('/admin-api/system/auth/login', { username: 'admin', password: env.VIBE_ADMIN_PASSWORD })).accessToken;
  member = (await api('/app-api/member/auth/login', { mobile: '13900000001', password: env.VIBE_MEMBER_PASSWORD })).accessToken;
  const session = await get(`/session/get?id=${fixture.trial.sessionIds[0]}`);
  const assignmentId = await post('/assignment/create', { cohortId: fixture.trial.id, sessionId: session.id, title: marker, description: 'TEST UI regression only', status: 'PUBLISHED', materials: [] });
  const draft = await api('/app-api/edu/submission/save', { studentId: fixture.studentId, assignmentId, content: 'TEST-only work for optimistic teacher feedback', attachments: [] });
  const submission = await api('/app-api/edu/submission/submit', { id: draft.id, revision: draft.revision, studentId: fixture.studentId, assignmentId, content: draft.content, attachments: [] });
  report.fixtures = { submissionId: submission.id, assignmentId, sessionId: session.id, enrollmentId: fixture.enrollmentId };
  await page.goto('http://127.0.0.1:49090/login');
  await page.getByRole('textbox', { name: '请输入密码', exact: true }).fill(env.VIBE_ADMIN_PASSWORD);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.waitForURL(url => !url.pathname.includes('/login'));
  await page.goto('http://127.0.0.1:49090/edu/submission');
  const row = page.getByRole('row').filter({ hasText: marker });
  await row.getByRole('button', { name: '开始批改', exact: true }).click();
  const drawer = page.locator('.el-drawer:visible');
  await drawer.getByText('尚未保存反馈草稿', { exact: true }).waitFor();
  assert.equal(await drawer.getByText(/服务器保存时间/).count(), 0);
  const feedback = drawer.locator('textarea');
  await feedback.fill(marker + ' first draft');
  await drawer.getByText('邀请学员修改后再次提交', { exact: true }).click();
  const savedResponse = page.waitForResponse(r => r.url().endsWith('/edu/submission/review') && r.request().method() === 'POST');
  await drawer.getByRole('button', { name: '保存批改草稿', exact: true }).click();
  const saved = await (await savedResponse).json();
  assert.equal(saved.code, 0, saved.msg);
  assert.equal(saved.data.revision, 1);
  await drawer.getByText(/草稿服务器保存时间/).waitFor();
  assert((await drawer.getByText(/草稿服务器保存时间/).textContent()).includes(new Date(saved.data.updateTime).toLocaleString('zh-CN', { hour12: false })));
  pass('New review never claims saved; draft save sends revision 0 and displays actual server time');
  await drawer.getByRole('button', { name: '关闭', exact: true }).click();
  await row.getByRole('button', { name: '开始批改', exact: true }).click();
  assert.equal(await feedback.inputValue(), marker + ' first draft');
  assert(await drawer.getByRole('checkbox').isChecked());
  const reopened = await get(`/submission/get?id=${submission.id}`);
  await post('/submission/review', { id: submission.id, revision: reopened.review.revision, feedback: marker + ' other editor', requireRevision: false, status: 'DRAFT' });
  await feedback.fill(marker + ' preserve this local draft');
  const conflictResponse = page.waitForResponse(r => r.url().endsWith('/edu/submission/review') && r.request().method() === 'POST');
  await drawer.getByRole('button', { name: '保存批改草稿', exact: true }).click();
  const conflict = await (await conflictResponse).json();
  assert.notEqual(conflict.code, 0);
  assert.equal(await feedback.inputValue(), marker + ' preserve this local draft');
  assert(await drawer.getByRole('checkbox').isChecked());
  await drawer.getByText(/有尚未保存的修改/).waitFor();
  await page.screenshot({ path: '.runtime/admin-review-conflict-live.png', fullPage: true, animations: 'disabled' });
  pass('Reopened draft hydrates feedback/requireRevision; real competing update rejects stale revision and preserves local input');
  const latest = await get(`/submission/get?id=${submission.id}`);
  await post('/submission/review', { id: submission.id, revision: latest.review.revision, feedback: 'TEST completed teaching UI regression', requireRevision: false, status: 'PUBLISHED' });
  await page.goto(`http://127.0.0.1:49090/edu/session?cohortId=${fixture.trial.id}`);
  const sessionRow = page.getByRole('row').filter({ hasText: session.title });
  await sessionRow.getByRole('button', { name: '记出勤', exact: true }).click();
  let attendance = page.locator('.el-drawer:visible');
  await attendance.locator('.el-loading-mask').waitFor({ state: 'hidden' }).catch(() => {});
  const actualRows = attendance.locator('.el-table__body-wrapper .el-table__row');
  const roster = await get(`/enrollment/page?pageNo=1&pageSize=100&cohortId=${fixture.trial.id}&sessionId=${session.id}&status=ACTIVE`);
  const studentName = roster.list.find(e => e.id === fixture.enrollmentId).studentName;
  const targetRow = actualRows.filter({ hasText: studentName });
  await targetRow.locator('.el-select').click();
  await page.getByRole('option', { name: '出勤', exact: true }).click();
  await targetRow.getByPlaceholder('可选备注').fill(marker);
  await attendance.getByRole('button', { name: '保存出勤', exact: true }).click();
  await attendance.waitFor({ state: 'hidden' });
  const attendanceQuery = page.waitForRequest(r => r.url().includes('/edu/enrollment/page') && r.url().includes(`sessionId=${session.id}`));
  await sessionRow.getByRole('button', { name: '记出勤', exact: true }).click();
  await attendanceQuery;
  await targetRow.getByPlaceholder('可选备注').waitFor();
  assert.equal(await targetRow.getByPlaceholder('可选备注').inputValue(), marker);
  assert((await targetRow.textContent()).includes('出勤'));
  await targetRow.getByText(/已保存/).waitFor();
  pass('Attendance reopening requests exact session and restores persisted status/note/server timestamp');
  await attendance.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByText('月历', { exact: true }).click();
  const month = new Date(session.startTime);
  const monthKey = `${month.getFullYear()}-${String(month.getMonth() + 1).padStart(2, '0')}`;
  await page.locator('.calendar-toolbar input').fill(monthKey);
  await page.locator('.calendar-toolbar input').press('Enter');
  const calendarSession = page.locator('.calendar-session').filter({ hasText: session.title });
  await calendarSession.waitFor();
  assert.equal(await page.locator('.el-table:visible').count(), 0);
  await page.screenshot({ path: '.runtime/admin-session-calendar-live.png', fullPage: true, animations: 'disabled' });
  pass('Month calendar displays actual session on selected month using original API and hides paginated table');
  await calendarSession.getByRole('button', { name: '调整', exact: true }).click();
  const editDrawer = page.locator('.el-drawer:visible');
  const previewResponse = page.waitForResponse(r => r.url().endsWith('/edu/session/preview'));
  await editDrawer.getByRole('button', { name: '检查冲突与影响', exact: true }).click();
  const preview = await (await previewResponse).json();
  assert.equal(preview.code, 0, preview.msg);
  const dialog = page.getByRole('dialog', { name: '确认本次排课影响', exact: true });
  await dialog.getByText('原上课时间', { exact: true }).waitFor();
  assert.equal(preview.data.canSave, true);
  await dialog.getByText(studentName, { exact: true }).waitFor();
  const before = await get(`/session/get?id=${session.id}`);
  assert.equal(before.version, session.version, 'Preview must not mutate version');
  await page.screenshot({ path: '.runtime/admin-session-impact-live.png', fullPage: true, animations: 'disabled' });
  await dialog.getByRole('button', { name: '返回调整', exact: true }).click();
  await editDrawer.getByLabel('课次标题', { exact: true }).fill(session.title + ' TEST updated preview');
  const recheck = page.waitForResponse(r => r.url().endsWith('/edu/session/preview'));
  await editDrawer.getByRole('button', { name: '检查冲突与影响', exact: true }).click();
  const rechecked = await recheck;
  assert.equal(rechecked.request().postDataJSON().title, session.title + ' TEST updated preview');
  assert.equal((await get(`/session/get?id=${session.id}`)).title, session.title);
  pass('Nonmutating schedule preview shows old/new times and real impacted learners; form edits require new candidate check');
  assert.deepEqual(errors, []);
  report.status = 'PASSED';
} catch (error) {
  report.status = 'FAILED'; report.error = error.message;
  await page.screenshot({ path: '.runtime/admin-teaching-ui-failure.png', fullPage: true }).catch(() => {});
  throw error;
} finally {
  fs.writeFileSync('.runtime/education-admin-teaching-ui-report.json', JSON.stringify(report, null, 2) + '\n');
  await browser.close();
}
